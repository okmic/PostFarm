export const generateSimpleHeadlinePrompt = (
  topic: string,
  type: HeadlineContentEnum,
  style: HeadlineStyleEnum
): string => {
  const normalizedType = (type as string).toUpperCase()
  const normalizedStyle = (style as string).toUpperCase()

  const styleMap: Record<string, string> = {
    VIRAL: 'шокируй, используй цифры и срочность',
    EMOTIONAL: 'надави на эмпатию, расскажи историю',
    PROVOCATIVE: 'вызови спор, брось вызов',
    EDUCATIONAL: 'дай пользу, используй цифры и факты'
  }

  const typeMap: Record<string, { label: string, length: string }> = {
    HEADLINES: { label: 'заголовок', length: '12–18 слов' },
    HOOKS: { label: 'хук', length: '5–10 слов' },
    CTA: { label: 'CTA', length: '8–15 слов' },
    VIRAL: { label: 'вирусную идею', length: '20–30 слов' }
  }

  const t = typeMap[normalizedType] || typeMap.HEADLINES

  return `Создай 10 вариантов ${t.label}ов для Telegram-поста на тему «${topic}».

Стиль: ${styleMap[normalizedStyle] || styleMap.VIRAL}

Правила:
- Длина каждого: ${t.length}
- 1–2 эмодзи
- Конкретика (цифры, детали)
- Каждый вариант — уникальная механика

Оцени каждый вариант по 3 критериям (эмоция, конкретика, релевантность теме).
Выбери ПОБЕДИТЕЛЯ с суммой ≥ 24 баллов и объясни почему он лучший.

Формат:
🏆 ПОБЕДИТЕЛЬ: [лучший вариант]
📊 ПОЧЕМУ ОН: [аргументация]
📋 ОСТАЛЬНЫЕ (от лучшего к худшему):
[варианты с баллами]`
}