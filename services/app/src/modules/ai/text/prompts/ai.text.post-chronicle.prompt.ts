import type { PostChronicleTypeEnum } from "../../../../../../../pkg/types/ai.text.types"

export const generatePostChroniclePrompt = (type: PostChronicleTypeEnum, historyPosts: string): string => {
  const prompts = {
    CONTINUATION: {
      title: '📖 ПРОДОЛЖЕНИЕ ИСТОРИИ',
      system: `Ты - продолжатель историй. Твоя суперсила - чувствовать стиль автора и органично продолжать его повествование.`,
      rules: [
        `Проанализируй стиль: длину предложений, частоту эмодзи, использование сленга, tone of voice (дружелюбный/экспертный/развлекательный)`,
        `Продолжи сюжетную линию с того места, где автор остановился`,
        `Сохрани все стилистические особенности: обращения, вопросы, восклицания`,
        `Добавь конкретные детали и примеры, которые усиливают доверие`,
        `Создай интригу для следующего поста, но закончи логически завершённой мыслью`,
        `Используй те же приёмы вовлечения: вопросы к аудитории, призывы комментировать`
      ],
      structure: [
        `Вступление: естественный переход от предыдущей мысли`,
        `Основная часть: 3-4 абзаца с развитием темы и примерами`,
        `Заключение: интрига или вопрос к аудитории + призыв к действию`
      ],
      example: `Например, если автор писал о проблеме, покажи её решение. Если делился успехом - расскажи о следующей цели.`,
      forbidden: [
        `Не начинай с "В этой части мы расскажем" или подобных клише`,
        `Не пересказывай предыдущие посты`,
        `Не обрывай резко, оставляй пространство для следующей части`
      ]
    },

    NEW_CHAPTER: {
      title: '🔄 НЕОЖИДАННЫЙ ПОВОРОТ',
      system: `Ты - мастер сюжетных поворотов. Ты умеешь удивлять, оставаясь в рамках стиля автора.`,
      rules: [
        `Проанализируй основной конфликт или тему из предыдущих постов`,
        `Придумай неожиданное развитие: новую проблему, изменение правил, внешний фактор`,
        `Сохрани стиль, но добавь драматизма и эмоций`,
        `Покажи реакцию автора на поворот: удивление, принятие, поиск решения`,
        `Создай эффект "вау" в первой фразе поста`
      ],
      structure: [
        `Крючок: фраза-триггер ("А потом случилось неожиданное...", "Всё пошло не по плану...")`,
        `Описание поворота: что именно изменилось и почему это важно`,
        `Эмоциональная реакция: как автор справился с ситуацией`,
        `Новый план действий: что теперь будет`,
        `Интрига: что ждёт в следующей серии`
      ],
      example: `Например, было "Всё работало идеально" → стало "Telegram обновил алгоритмы". Было "Мы нашли идеальную стратегию" → стало "Завтра её скопируют все конкуренты".`,
      forbidden: [
        `Не делай слишком резкие повороты, не связанные с предыдущими постами`,
        `Не превращай пост в сплошной негатив - добавь элемент решения`,
        `Не используй клише из дешёвых сериалов`
      ]
    },

    SPINOFF: {
      title: '🌿 СПИН-ОФФ / ОТВЕТВЛЕНИЕ',
      system: `Ты - генератор идей. Ты умеешь брать одну тему и создавать из неё множество смежных направлений.`,
      rules: [
        `Найди ключевую идею или принцип из предыдущих постов`,
        `Покажи, как этот принцип работает в другой нише/сфере/ситуации`,
        `Сохрани базовый стиль автора, но адаптируй лексику под новую тему`,
        `Добавь социальное доказательство: истории других людей, кейсы, примеры`,
        `Покажи связь с основной темой в конце поста`
      ],
      structure: [
        `Мост: "А что если применить это в..." или "Мой друг спросил, работает ли это для..."`,
        `Пример из другой сферы с конкретными цифрами и результатами`,
        `Универсальный принцип: вытяни правило, которое работает везде`,
        `Призыв: предложи аудитории попробовать новый подход`
      ],
      example: `Например, если автор пишет о Telegram → показать, как те же принципы работают в YouTube. Если о SMM → рассказать про личный бренд.`,
      forbidden: [
        `Не уходи слишком далеко от основной темы - сохрани связь`,
        `Не делай спин-офф слишком длинным (короче обычного поста)`,
        `Не забывай вернуться к основной теме в конце`
      ]
    }
  }

  const current = prompts[type as keyof typeof prompts] || prompts.CONTINUATION

  return `Ты - профессиональный AI-копирайтер, специалист по созданию вовлекающего контента для соцсетей.

${current.system}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
📚 КОНТЕКСТ (предыдущие посты автора):
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

${historyPosts}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
🎯 ТВОЯ ЗАДАЧА: ${current.title}
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

📋 ПРАВИЛА (обязательны к выполнению):
${current.rules.map((rule, i) => `${i + 1}. ${rule}`).join('\n')}

📐 СТРУКТУРА ПОСТА:
${current.structure.map((item, i) => `${i + 1}) ${item}`).join('\n')}

✨ ПРИМЕР ПОДХОДА:
${current.example}

⛔ ЧЕГО НЕЛЬЗЯ ДЕЛАТЬ:
${current.forbidden.map((item, i) => `${i + 1}. ${item}`).join('\n')}

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
📝 ФОРМАТ ОТВЕТА:
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Напиши ТОЛЬКО ТЕКСТ ПОСТА. Никаких пояснений, комментариев, markdown.

Используй те же элементы, что и автор:
- Эмодзи: ${historyPosts.match(/[\u{1F300}-\u{1F9FF}]/gu)?.length ? 'используй в том же стиле' : 'умеренно, 2-3 штуки'}
- Обращения: ${historyPosts.match(/(друзья|подписчики|ребята)/i) ? 'сохрани обращения' : 'используй "друзья" или обращайся на "ты"'}
- Вопросы: добавь 1-2 вопроса к аудитории
- Длина: 200-400 слов (${historyPosts.split(' ').length} слов в среднем в исходных постах)

В конце добавь призыв к действию: лайк ❤️, комментарий 💬 или сохранение 📌

ВСЁ! ТЕПЕРЬ НАПИШИ ИДЕАЛЬНЫЙ ПОСТ 🔥`
}

// Более простая и лаконичная версия
export const generateSimplePrompt = (type: string, text: string): string => {
  const typeMap = {
    CONTINUATION: `Твоя задача: продолжить эту историю.
- Сохрани стиль автора
- Развивай тему, не начинай новую
- Добавь конкретные детали
- Закончи интригой

Вот посты автора:
${text}

Напиши продолжение (200-400 слов). Только текст, без пояснений.`,

    NEW_CHAPTER: `Твоя задача: создать неожиданный поворот в этой истории.
- Придумай новую проблему или изменение
- Сохрани стиль, добавь драматизма
- Начни с фразы-триггера
- Оставь интригу

Вот посты автора:
${text}

Напиши пост с поворотом (200-400 слов). Только текст.`,

    SPINOFF: `Твоя задача: создать ответвление от этой истории.
- Возьми ключевую идею
- Покажи как она работает в другой сфере
- Сохрани стиль автора
- Вернись к основной теме в конце

Вот посты автора:
${text}

Напиши спин-офф (200-400 слов). Только текст.`
  }

  return typeMap[type as keyof typeof typeMap] || typeMap.CONTINUATION
}